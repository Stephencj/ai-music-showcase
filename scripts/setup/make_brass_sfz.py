"""Write SFZ maps for the VSCO 2 CE trumpet and tenor trombone samples.

VSCO 2 CE ships raw WAVs named like ``Sum_SHTrumpet_stac_A#3_v2_rr1.wav``
(note, dynamic layer, round robin) but no SFZ. This writes one map per
articulation plus ``horns_stac.sfz``, a two-piece horn section (trombone
below the split, trumpet above) for funk stabs.

The file names use the C3 = middle C convention, an octave below the SFZ /
MIDI numbering the player uses (c4 = 60); measured pitches confirm it.

    python scripts/setup/make_brass_sfz.py data/instruments/vsco2-ce
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

NOTES = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6,
         "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}
NAME = re.compile(r"_([A-G]#?)(-?\d+)_v(\d+)(?:_rr(\d+))?\.wav$", re.I)
NAME_OCTAVE_SHIFT = 12      # file "A3" sounds as MIDI A4 (69)
SPLIT = 58                  # horn section: trombone below, trumpet from Bb3


def scan(folder: Path) -> dict[int, dict[int, list[Path]]]:
    """note → layer → round-robin samples."""
    notes: dict[int, dict[int, list[Path]]] = defaultdict(lambda: defaultdict(list))
    for wav in sorted(folder.glob("*.wav")):
        m = NAME.search(wav.name)
        if not m:
            continue
        note = NOTES[m.group(1).upper()] + 12 * (int(m.group(2)) + 1) + NAME_OCTAVE_SHIFT
        notes[note][int(m.group(3))].append(wav)
    return notes


def regions(folder: Path, base: Path, lo_limit: int = 0, hi_limit: int = 127,
            release: float = 0.12) -> list[str]:
    notes = scan(folder)
    keys = sorted(k for k in notes if lo_limit - 12 <= k <= hi_limit + 12)
    out: list[str] = []
    for i, key in enumerate(keys):
        lo = lo_limit if i == 0 else (keys[i - 1] + key) // 2 + 1
        hi = hi_limit if i == len(keys) - 1 else (key + keys[i + 1]) // 2
        lo, hi = max(lo, lo_limit), min(hi, hi_limit)
        if lo > hi:
            continue
        layers = sorted(notes[key])
        for li, layer in enumerate(layers):
            lovel = 1 + (127 * li) // len(layers)
            hivel = (127 * (li + 1)) // len(layers)
            rrs = notes[key][layer]
            for ri, wav in enumerate(rrs):
                out.append(
                    f"<region> sample={wav.relative_to(base).as_posix()} "
                    f"lokey={lo} hikey={hi} pitch_keycenter={key} "
                    f"lovel={lovel} hivel={hivel} seq_length={len(rrs)} seq_position={ri + 1} "
                    f"ampeg_release={release}"
                )
    return out


def write(path: Path, header: str, body: list[str]) -> None:
    if not body:
        print(f"skipped {path.name}: no samples matched")
        return
    path.write_text(header + "\n" + "\n".join(body) + "\n")
    print(f"wrote {path} ({len(body)} regions)")


def main(root: str) -> None:
    base = Path(root).resolve()
    trumpet, trombone = base / "Brass" / "Trumpet", base / "Brass" / "Tenor Trombone"
    head = ("// Generated by scripts/setup/make_brass_sfz.py from VSCO 2 CE (CC0).\n"
            "<global> amp_veltrack=45")
    write(base / "trumpet_stac.sfz", head, regions(trumpet / "stac", base))
    write(base / "trombone_stac.sfz", head, regions(trombone / "stac", base))
    write(base / "trumpet_sus.sfz", head, regions(trumpet / "sus", base, release=0.25))
    write(base / "trombone_sus.sfz", head, regions(trombone / "sus", base, release=0.25))
    write(base / "horns_stac.sfz", head,
          regions(trombone / "stac", base, hi_limit=SPLIT - 1)
          + regions(trumpet / "stac", base, lo_limit=SPLIT))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/instruments/vsco2-ce")
