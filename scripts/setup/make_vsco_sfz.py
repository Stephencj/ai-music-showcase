"""Write SFZ maps for VSCO 2 CE sample folders (sustains for strings and horn).

VSCO ships WAVs named like ``VlnEns_susVib_A2_v1.wav`` or
``susvib_A2_v1_1.wav`` (note, dynamic layer, optional round robin) without
SFZ maps, and its octave naming isn't consistent between instruments, so
each folder's octave shift is measured (YIN on a few samples) rather than
assumed.

Download the four sustain folders first (sparse, ~230 MB):

    cd data/instruments
    git clone --depth 1 --filter=blob:none --sparse https://github.com/sgossner/VSCO-2-CE.git vsco2-ce-strings
    cd vsco2-ce-strings && git sparse-checkout set "Strings/Violin Section/susVib" \
        "Strings/Viola Section/susvib" "Strings/Cello Section/susvib" "Brass/F Horn/sus" \
        "Strings/Violin Section/Spic" "Strings/Viola Section/spic" "Strings/Cello Section/spic" && rm -rf .git

    python scripts/setup/make_vsco_sfz.py data/instruments/vsco2-ce-strings
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

NOTES = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}
NAME = re.compile(r"_([A-G]#?)(-?\d+)_v(\d+)(?:_(?:rr)?(\d+))?\.wav$", re.I)

# (output file, folder, attack s, release s)
MAPS = [
    ("violins_sus.sfz", "Strings/Violin Section/susVib", 0.12, 0.5),
    ("violas_sus.sfz", "Strings/Viola Section/susvib", 0.12, 0.5),
    ("cellos_sus.sfz", "Strings/Cello Section/susvib", 0.12, 0.5),
    ("french_horn_sus.sfz", "Brass/F Horn/sus", 0.06, 0.35),
    ("violins_spic.sfz", "Strings/Violin Section/Spic", 0.002, 0.12),
    ("violas_spic.sfz", "Strings/Viola Section/spic", 0.002, 0.12),
    ("cellos_spic.sfz", "Strings/Cello Section/spic", 0.002, 0.12),
]

# Combined section maps: cellos below G3, violas to F#4, violins above.
SECTIONS = {
    "strings_section_sus.sfz": ("cellos_sus.sfz", "violas_sus.sfz", "violins_sus.sfz"),
    "strings_section_spic.sfz": ("cellos_spic.sfz", "violas_spic.sfz", "violins_spic.sfz"),
}


def named_midi(m: re.Match) -> int:
    return NOTES[m.group(1).upper()] + 12 * (int(m.group(2)) + 1)


def octave_shift(files: list[Path]) -> int:
    """Measured pitch minus named pitch, rounded to whole octaves."""
    import librosa
    import soundfile as sf
    diffs = []
    for f in files[:: max(1, len(files) // 6)][:6]:
        m = NAME.search(f.name)
        x, sr = sf.read(str(f), always_2d=True)
        x = x.mean(axis=1)
        a = int(np.argmax(np.abs(x) > 0.1 * np.abs(x).max()))
        seg = x[a + int(0.2 * sr): a + int(0.8 * sr)]
        if len(seg) < 4096:
            continue
        hz = librosa.yin(seg, fmin=40, fmax=2000, sr=sr, frame_length=4096)
        measured = 69 + 12 * np.log2(np.median(hz) / 440.0)
        diffs.append(measured - named_midi(m))
    return int(12 * round(float(np.median(diffs)) / 12)) if diffs else 0


def build(folder: Path, base: Path, attack: float, release: float) -> tuple[list[str], int]:
    files = sorted(p for p in folder.glob("*.wav") if NAME.search(p.name))
    shift = octave_shift(files)
    notes: dict[int, dict[int, list[Path]]] = defaultdict(lambda: defaultdict(list))
    for f in files:
        m = NAME.search(f.name)
        notes[named_midi(m) + shift][int(m.group(3))].append(f)
    keys = sorted(notes)
    out = []
    for i, key in enumerate(keys):
        lo = 0 if i == 0 else (keys[i - 1] + key) // 2 + 1
        hi = 127 if i == len(keys) - 1 else (key + keys[i + 1]) // 2
        layers = sorted(notes[key])
        for li, layer in enumerate(layers):
            lovel, hivel = 1 + (127 * li) // len(layers), (127 * (li + 1)) // len(layers)
            rrs = notes[key][layer]
            for ri, f in enumerate(rrs):
                out.append(f"<region> sample={f.relative_to(base).as_posix()} lokey={lo} hikey={hi} "
                           f"pitch_keycenter={key} lovel={lovel} hivel={hivel} seq_length={len(rrs)} "
                           f"seq_position={ri + 1} ampeg_attack={attack} ampeg_release={release} loop_mode=no_loop")
    return out, shift


def main(root: str) -> None:
    base = Path(root).resolve()
    for name, folder, attack, release in MAPS:
        path = base / folder
        if not path.exists():
            print(f"skipped {name}: {folder} not downloaded")
            continue
        regions, shift = build(path, base, attack, release)
        (base / name).write_text("// Generated by scripts/setup/make_vsco_sfz.py from VSCO 2 CE (CC0).\n"
                                 "<global> amp_veltrack=60\n" + "\n".join(regions) + "\n")
        print(f"wrote {name}: {len(regions)} regions, names shifted {shift:+d} semitones")
    for name, parts in SECTIONS.items():
        write_section(base, name, parts)


def write_section(base: Path, name: str, parts: tuple[str, str, str]) -> None:
    """One string-section map: cellos below G3, violas to F#4, violins above."""
    ranges = ((parts[0], 0, 54), (parts[1], 55, 66), (parts[2], 67, 127))
    out = ["// String section from make_vsco_sfz maps (VSCO 2 CE, CC0).", "<global> amp_veltrack=60"]
    for part, lo, hi in ranges:
        if not (base / part).exists():
            return
        for line in (base / part).read_text().splitlines():
            if not line.startswith("<region>"):
                continue
            a = int(re.search(r"lokey=(\d+)", line).group(1))
            b = int(re.search(r"hikey=(\d+)", line).group(1))
            a2, b2 = max(a, lo), min(b, hi)
            if a2 > b2:
                continue
            out.append(re.sub(r"hikey=\d+", f"hikey={b2}", re.sub(r"lokey=\d+", f"lokey={a2}", line)))
    (base / name).write_text("\n".join(out) + "\n")
    print(f"wrote {name}: {len(out) - 2} regions")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/instruments/vsco2-ce-strings")
